import type { Metadata, Viewport } from 'next';
import { Host_Grotesk, Atkinson_Hyperlegible_Mono } from 'next/font/google';
import './globals.css';
import { Toaster } from 'sonner';
import { UserLimitsProvider } from '@/hooks/UserLimitsContext';
import { APP_NAME, APP_URL } from '@/lib/utils';
import PlausibleProvider from 'next-plausible';
import { ThemeProvider } from 'next-themes';

const host = Host_Grotesk({
  variable: '--font-host',
  weight: ['400', '500'],
  subsets: ['latin'],
});

const atkinson = Atkinson_Hyperlegible_Mono({
  variable: '--font-atkinson',
  weight: ['400', '500'],
  subsets: ['latin'],
  adjustFontFallback: false,
});

export const metadata: Metadata = {
  metadataBase: new URL(APP_URL),
  title: `${APP_NAME} — ask the file, read the chart`,
  description:
    'Upload a CSV, ask in plain english, and read the chart. A model writes the python, runs it in a sandbox, and shows its work.',
  alternates: { canonical: '/' },
  openGraph: {
    type: 'website',
    url: APP_URL,
    title: `${APP_NAME} — the file holds the answer`,
    description:
      'Upload a CSV, ask in plain english, and read the chart. The exact code comes with it.',
    // the og card is generated by src/app/opengraph-image.tsx
  },
  twitter: { card: 'summary_large_image' },
};

export const viewport: Viewport = {
  width: 'device-width',
  initialScale: 1,
  themeColor: [
    { media: '(prefers-color-scheme: dark)', color: '#22262b' },
    { media: '(prefers-color-scheme: light)', color: '#faf8f4' },
  ],
};

export default function RootLayout({
  children,
}: Readonly<{ children: React.ReactNode }>) {
  return (
    <html
      lang='en'
      suppressHydrationWarning
      className={`${host.variable} ${atkinson.variable}`}
    >
      <head>
        {process.env.NEXT_PUBLIC_PLAUSIBLE_DOMAIN && (
          <PlausibleProvider
            src='https://plausible.io/js/script.js'
            scriptProps={
              {
                'data-domain': process.env.NEXT_PUBLIC_PLAUSIBLE_DOMAIN,
              } as unknown as React.ComponentProps<
                typeof PlausibleProvider
              >['scriptProps']
            }
          />
        )}
        {/* theme class before paint; same storage key as always */}
        <script
          dangerouslySetInnerHTML={{
            __html: `(function(){try{var t=localStorage.getItem('datagraph-theme')||'light';document.documentElement.classList.add(t);}catch(e){document.documentElement.classList.add('light');}})();`,
          }}
        />
      </head>
      <body>
        <ThemeProvider attribute='class' defaultTheme='light' enableSystem={false} storageKey='datagraph-theme'>
          <UserLimitsProvider>
            {children}
            <Toaster
              position='bottom-right'
              toastOptions={{
                style: {
                  background: 'var(--color-paper-2)',
                  color: 'var(--color-ink)',
                  border: '1px solid var(--color-rule)',
                  borderRadius: 'var(--radius-card)',
                  fontFamily: 'var(--font-body)',
                  fontSize: '14px',
                },
              }}
            />
          </UserLimitsProvider>
        </ThemeProvider>
      </body>
    </html>
  );
}
